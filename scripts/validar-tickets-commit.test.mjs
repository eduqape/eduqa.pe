import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";

function validar(mensaje) {
  return spawnSync(process.execPath, ["scripts/validar-tickets-commit.mjs"], {
    cwd: process.cwd(),
    input: mensaje,
    encoding: "utf8",
  });
}

assert.equal(validar("[fix] (ui): corregir buscador\n\nRefs: #6\n").status, 0);
assert.equal(validar("[feat] (cursos): agregar códigos\n\nCloses: #2, #3\n").status, 0);
assert.equal(validar("[fix] (ui): corregir buscador\n").status, 1);
assert.match(validar("[fix] (ui): corregir buscador\n").stderr, /no vincula un ticket/);
assert.equal(
  validar("[fix] (ui): primero\n\nRefs: #6\0[fix] (pdf): segundo\n").status,
  1,
  "Cada commit del push debe vincular al menos un ticket",
);

const firmada = "[feat] (cursos): curso nuevo\n\nRefs: #6\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n";
assert.equal(validar(firmada).status, 1);
assert.match(validar(firmada).stderr, /Generated with Claude Code/);
assert.equal(validar("[feat] (cursos): curso nuevo\n\nRefs: #6\n\nGenerated with Claude Code\n").status, 1);
assert.equal(
  validar("[fix] (ui): primero\n\nRefs: #6\0[fix] (pdf): segundo\n\nRefs: #7\n\ngenerated by claude code\n").status,
  1,
  "La firma se rechaza en cualquier commit del push, no solo en el primero",
);
const coautorada = "[feat] (cursos): curso nuevo\n\nRefs: #6\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n";
assert.equal(validar(coautorada).status, 1);
assert.match(validar(coautorada).stderr, /Co-Authored-By: Claude/);
assert.equal(
  validar("[fix] (ui): primero\n\nRefs: #6\0[fix] (pdf): segundo\n\nRefs: #7\n\nco-authored-by: Claude Sonnet 5 <noreply@anthropic.com>\n").status,
  1,
  "Claude como coautor se rechaza con cualquier modelo y en cualquier commit del push",
);
assert.equal(
  validar("[fix] (ui): corregir buscador\n\nRefs: #6\n\nCo-Authored-By: Asistente <noreply@anthropic.com>\n").status,
  1,
  "El correo de Anthropic basta para reconocer al coautor",
);
assert.equal(
  validar("[fix] (ui): corregir buscador\n\nRefs: #6\n\nCo-Authored-By: Ana Pérez <ana@example.com>\n").status,
  0,
  "Un coautor humano sigue permitido",
);
